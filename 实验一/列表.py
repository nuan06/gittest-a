print("请输入一个列表(以空格分隔): ")
input_list = input("列表: ")
print("你输入的列表是: ", input_list)
data = list(map(float, input_list.split()))
sorted_data = sorted(data)
print("排序后的列表是: ", sorted_data)
max_value = max(data)
min_value = min(data)
print("列表中的最大值是: ", max_value)
print("列表中的最小值是: ", min_value)
avg_value = sum(data) / len(data)
print("列表中的平均值是: ", avg_value)